 * ⚠ `User::checkAccess` در حال حاضر به خاطر یک باگ قدیمی چیزی را واقعاً
 * چک نمی‌کند؛ این ثابت‌ها درست‌اند ولی اجرایشان به رفع آن باگ (ایشوی امنیتی) وابسته است.
 */
